const crypto = require('node:crypto');
const fs = require('node:fs');
const path = require('node:path');

const root = path.resolve(__dirname, '..');
const migrationsDir = path.join(root, 'supabase', 'migrations');
const outputPath = path.join(root, 'docs', 'supabase', 'SCHEMA_AND_POLICY_INVENTORY.md');
const migrations = fs.readdirSync(migrationsDir).filter((name) => name.endsWith('.sql')).sort();
const rows = migrations.map((name) => {
  const source = fs.readFileSync(path.join(migrationsDir, name), 'utf8').replace(/\r\n/g, '\n');
  const sha256 = crypto.createHash('sha256').update(source).digest('hex');
  return `| \`${name}\` | \`${sha256}\` |`;
});
const contents = [
  '# Canonical Supabase Schema and Policy Inventory',
  '',
  '> Generated by `npm run supabase:docs:update`. Do not edit manually.',
  '',
  'The ordered, immutable migrations below are the canonical database and RLS policy source. A local database rebuilt with `npm run supabase:reset` is the executable representation of this inventory. `schema.sql` is retained only as historical clean-install reference material and must not override a later migration.',
  '',
  '## Applied migration manifest',
  '',
  '| Migration | SHA-256 |',
  '| --- | --- |',
  ...rows,
  '',
  '## Regeneration',
  '',
  'Run `npm run supabase:docs:update` after adding a forward migration. CI runs `npm run supabase:docs:check` after rebuilding local Supabase, so an undocumented migration cannot merge.',
  '',
].join('\n');

if (process.argv.includes('--check')) {
  if (!fs.existsSync(outputPath) || fs.readFileSync(outputPath, 'utf8') !== contents) {
    throw new Error('Supabase schema/policy inventory is stale. Run npm run supabase:docs:update.');
  }
} else {
  fs.writeFileSync(outputPath, contents, 'utf8');
}
console.log(`${process.argv.includes('--check') ? 'Verified' : 'Generated'} ${path.relative(root, outputPath)}.`);
